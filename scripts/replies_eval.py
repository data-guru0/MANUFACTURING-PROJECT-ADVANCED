"""S15 evaluation (no LLM): are the customers' replies routed right, and are the lost reasons in Odoo?

Ground truth: the simulated customers (legacy/traffic/customer_responder.py) choose each reply's outcome from the
Message-ID of the email Apex sent them, so every reply to an agent-sent quote has a known true route. Lost reasons are
read back from Odoo through erp-mcp-read. Writes docs/fde/REPLIES_EVAL.md.

Usage: uv run python -m scripts.replies_eval
"""

import json
import subprocess
from pathlib import Path
from typing import Any

from legacy.traffic.customer_responder import outcome_for

REPO = Path(__file__).resolve().parents[1]
COMPOSE = [
    "docker",
    "compose",
    "-p",
    "apex",
    "-f",
    str(REPO / "docker-compose.legacy.yml"),
    "-f",
    str(REPO / "docker-compose.agent.yml"),
]
SQL = """SELECT coalesce(json_agg(t), '[]') FROM (
           SELECT r.email_id, r.result->>'route' AS route, r.result->>'quotation' AS quotation, r.result->>'detail' AS detail,
                  a.result->>'message_id' AS apex_message_id, a.result ? 'quotation' AS quoted, ri.route AS review_route
           FROM replies r JOIN emails e ON e.id = r.email_id
                LEFT JOIN actions a ON a.email_id = e.thread_id AND a.result ? 'message_id'
                LEFT JOIN review_items ri ON ri.email_id = r.email_id ORDER BY r.email_id) t"""


def sh(*args: str) -> str:
    r = subprocess.run([*COMPOSE, *args], capture_output=True, text=True, encoding="utf-8", timeout=300)
    if r.returncode:
        raise SystemExit(r.stderr[-1500:])
    return r.stdout.strip()


def evaluate() -> dict[str, Any]:
    rows = json.loads(sh("exec", "-T", "app-postgres", "psql", "-U", "apex", "-d", "apex", "-Atc", SQL))
    routed: list[dict[str, Any]] = []
    wrong: list[dict[str, Any]] = []
    declines: list[int] = []
    for r in rows:
        if r["apex_message_id"] and not r["quoted"]:  # a reply to a no-bid decline: no quotation, nothing to route
            declines.append(r["email_id"])
        elif r["apex_message_id"]:  # a reply to a quote the agent sent: the customer's true outcome is known
            truth = outcome_for(r["apex_message_id"])
            (routed if truth == r["route"] else wrong).append({**r, "truth": truth})
    rejects = [r for r in routed if r["route"] == "reject"]
    code = ("import json; from apex_agent.replies import tool; print(json.dumps({q: tool('erp-mcp-read', 'get_quotation', {'name': q}, "
            f"'reply_router') for q in {sorted({r['quotation'] for r in rejects})!r}}}))")  # fmt: skip
    odoo = json.loads(sh("exec", "-T", "worker", "python", "-c", code).splitlines()[-1]) if rejects else {}
    lost = [{"quotation": r["quotation"], "customer_said": r["detail"], "odoo_state": odoo[r["quotation"]]["state"],
             "odoo_lost_reason": odoo[r["quotation"]]["x_lost_reason"],
             "written_by_agent": f"customer email #{r['email_id']}" in (odoo[r["quotation"]]["x_lost_reason"] or "")} for r in rejects]  # fmt: skip
    late = [r for r in rows if r["review_route"] == "reply_accept_late"]
    return {"replies_with_truth": len(routed) + len(wrong), "routed_right": len(routed), "routed_wrong": wrong,
            "replies_to_declines": declines,
            "lost_reasons": lost, "late_acceptances_repriced": [r["quotation"] for r in late],
            "routes": {r["email_id"]: r["route"] for r in rows}}  # fmt: skip


def main() -> None:
    r = evaluate()
    out = REPO / "docs" / "fde" / "REPLIES_EVAL.md"
    out.write_text("\n".join([
        "# Replies to quotes (S15)", "",
        "_Generated by `uv run python -m scripts.replies_eval`. Truth: the simulated customers choose each outcome from the "
        "Message-ID of Apex's email (legacy/traffic/customer_responder.py). Lost reasons read back from Odoo. No LLM._", "",
        f"- Replies to agent-sent quotes: **{r['replies_with_truth']}**, routed right: **{r['routed_right']}**, wrong: **{len(r['routed_wrong'])}**",
        f"- Late acceptances re-priced: {', '.join(r['late_acceptances_repriced']) or 'none'}", "",
        "| Quotation | Customer said | Odoo state | Odoo lost reason | Written by the agent |", "|---|---|---|---|---|",
        *[f"| {x['quotation']} | {x['customer_said']} | {x['odoo_state']} | {x['odoo_lost_reason']} | {'yes' if x['written_by_agent'] else 'no (already lost)'} |"
          for x in r["lost_reasons"]], ""]), encoding="utf-8")  # fmt: skip
    print(json.dumps(r))


if __name__ == "__main__":
    main()
