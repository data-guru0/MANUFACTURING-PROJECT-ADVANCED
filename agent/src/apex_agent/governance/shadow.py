"""Shadow report (S20): the agent's drafts next to what Apex's people did for the SAME parts. No LLM.

Shadow mode = the agent drafts, sends nothing, and people quote as before. Where a person already quoted a part (the
repeats and revisions: Odoo's history), the two can be compared like for like:
    price      the agent's price for that part AT THE HUMAN QUOTE'S QUANTITY (S12) vs the human's price
    speed      the agent's time from RFQ to a draft ready for review vs the human's RFQ-to-quote time for that quote
Writes docs/fde/SHADOW_REPORT.md.

Usage (knowledge job): python -m apex_agent.governance.shadow
"""

import json
import os
from datetime import datetime
from pathlib import Path
from statistics import median
from typing import Any


def report(conn: Any) -> dict[str, Any]:
    rows = conn.execute("""
        SELECT e.email_id, e.part_code, e.result->'repeat',
               (SELECT extract(epoch FROM min(g.at) - m.ingested_at) / 60 FROM graph_events g WHERE g.email_id = e.email_id AND g.node = 'draft_reply')
        FROM estimates e JOIN emails m ON m.id = e.email_id
        WHERE e.result ? 'repeat' AND m.mailbox <> 'canary' ORDER BY e.email_id""").fetchall()  # fmt: skip
    human: dict[str, Any] = {}
    for (o,) in conn.execute("SELECT data FROM odoo_records WHERE model = 'sale.order'").fetchall():
        human[o["name"]] = o
    lines: dict[str, list[str]] = {}
    for (ln,) in conn.execute("SELECT data FROM odoo_records WHERE model = 'sale.order.line'").fetchall():
        if ln["product_id"] and ln["order_id"]:
            code = ln["product_id"][1].split("]")[0].lstrip("[")
            lines.setdefault(code, []).append(ln["order_id"][1])
    cases = []
    for email_id, part, rep, minutes in rows:
        if not rep or rep.get("old_unit_price") is None:
            continue
        orders = sorted(lines.get(rep["of"], []))
        o = human.get(orders[-1]) if orders else None
        days = None
        if o and o.get("x_rfq_received_at") and o.get("x_quote_sent_at"):
            days = round(
                (datetime.fromisoformat(o["x_quote_sent_at"]) - datetime.fromisoformat(o["x_rfq_received_at"])).total_seconds()
                / 86400,
                1,
            )
        same_qty = rep.get("today_at_old_qty") or (
            rep["new_unit_price"] if rep.get("old_qty") in (None, rep.get("new_qty")) else None
        )
        cases.append({"job": email_id, "part": part, "kind": rep["kind"], "of": rep["of"], "human_price": rep["old_unit_price"],
                      "human_qty": rep.get("old_qty"), "agent_price_same_qty": same_qty,
                      "diff_pct": round(100 * (same_qty - rep["old_unit_price"]) / rep["old_unit_price"], 1) if same_qty else None,
                      "human_days": days, "agent_minutes": round(float(minutes), 1) if minutes is not None else None})  # fmt: skip
    diffs = [abs(c["diff_pct"]) for c in cases if c["diff_pct"] is not None and c["kind"] == "repeat"]
    hd = [c["human_days"] for c in cases if c["human_days"] is not None]
    am = [c["agent_minutes"] for c in cases if c["agent_minutes"] is not None]
    return {"cases": cases, "repeats_compared": len(diffs), "median_abs_price_gap_pct_repeats": round(median(diffs), 1) if diffs else None,
            "median_human_days": round(median(hd), 1) if hd else None, "median_agent_minutes": round(median(am), 1) if am else None}  # fmt: skip


def main() -> dict[str, Any]:
    from apex_agent.knowledge import db

    r = report(db.connect())
    out = Path(os.environ.get("APEX_DOCS_DIR", "/app/docs-fde")) / "SHADOW_REPORT.md"
    out.write_text("\n".join([
        "# Shadow report (S20): the agent next to Apex's people, on the same parts", "",
        "_Generated by `python -m apex_agent.governance.shadow` (no LLM). The agent drafted; people quoted these parts before "
        "(Odoo history). Prices compared at the human quote's quantity; for a revision the part changed, so its gap includes the change._", "",
        f"- Repeats compared on price: **{r['repeats_compared']}**; median absolute gap agent vs human: **{r['median_abs_price_gap_pct_repeats']} %**",
        f"- Response: people took a median **{r['median_human_days']} days** (RFQ in → quote out) for these parts; the agent had a draft ready for "
        f"review in a median **{r['median_agent_minutes']} minutes** (a person still approves before anything is sent)", "",
        "| Job | Part | Kind | Human (qty) | Agent at that qty | Gap | Human days | Agent minutes |", "|---|---|---|---|---|---|---|---|",
        *[f"| {c['job']} | {c['part']} | {c['kind']} of {c['of']} | ${c['human_price']:.2f} ({c['human_qty']}) | "
          + (f"${c['agent_price_same_qty']:.2f}" if c["agent_price_same_qty"] else "-") + " | "
          + (f"{c['diff_pct']:+.1f} %" if c["diff_pct"] is not None else "-") + f" | {c['human_days']} | {c['agent_minutes']} |" for c in r["cases"]],
        "", "Reading it: a gap is not an error by itself. The human prices include gut-feel adjustments (W6) and old material prices "
        "(W8); the agent's are today's engine prices with every line sourced. Large gaps are where a person should look first.", ""]),
        encoding="utf-8")  # fmt: skip
    return {k: v for k, v in r.items() if k != "cases"}


if __name__ == "__main__":
    print(json.dumps(main(), default=str))
